import { resolve } from "node:path"
import { PALETTE_NAMES, type PaletteName, type ThemeTokens } from "@/types/docs"

const cssDirectory = resolve(import.meta.dir, "../node_modules/fumadocs-ui/css")
const outputPath = resolve(import.meta.dir, "../src/types/docs-palettes.ts")

function declarations(block: string): Record<string, string> {
    return Object.fromEntries(
        [...block.matchAll(/(--(?:color-fd|fd)-[\w-]+)\s*:\s*([^;{}]+);/g)].map(
            (match) => [match[1] ?? "", match[2]?.trim() ?? ""],
        ),
    )
}

function topLevelBlocks(css: string): Array<{ header: string; body: string }> {
    const blocks: Array<{ header: string; body: string }> = []
    let cursor = 0
    while (cursor < css.length) {
        const open = css.indexOf("{", cursor)
        if (open === -1) break
        let depth = 1
        let close = open + 1
        while (close < css.length && depth > 0) {
            if (css[close] === "{") depth += 1
            if (css[close] === "}") depth -= 1
            close += 1
        }
        if (depth !== 0) throw new Error("unbalanced palette CSS")
        const previousClose = css.lastIndexOf("}", open)
        const previousSemicolon = css.lastIndexOf(";", open)
        const start = Math.max(previousClose, previousSemicolon) + 1
        blocks.push({
            header: css.slice(start, open).trim(),
            body: css.slice(open + 1, close - 1),
        })
        cursor = close
    }
    return blocks
}

async function extractPalette(palette: PaletteName): Promise<ThemeTokens> {
    const css = await Bun.file(resolve(cssDirectory, `${palette}.css`)).text()
    const light: Record<string, string> = {}
    const dark: Record<string, string> = {}
    for (const block of topLevelBlocks(css)) {
        const values = declarations(block.body)
        const isTheme = /^@theme(?:\s+static)?$/.test(block.header)
        const selectors = block.header.split(",").map((value) => value.trim())
        if (isTheme || selectors.includes(":root")) Object.assign(light, values)
        if (selectors.includes(".dark")) Object.assign(dark, values)
    }

    const tokens: ThemeTokens = {}
    for (const name of [
        ...new Set([...Object.keys(light), ...Object.keys(dark)]),
    ].sort()) {
        const lightValue = light[name]
        const darkValue = dark[name]
        if (lightValue !== undefined && darkValue !== undefined) {
            tokens[name] =
                lightValue === darkValue
                    ? lightValue
                    : { light: lightValue, dark: darkValue }
        } else {
            tokens[name] = lightValue ?? darkValue ?? ""
        }
    }
    return tokens
}

const palettes: Record<string, ThemeTokens> = {}
for (const palette of PALETTE_NAMES)
    palettes[palette] = await extractPalette(palette)

const generated = `// GENERATED by scripts/extract-palette-tokens.ts — do not edit\nimport type { PaletteName, ThemeTokens } from "./docs"\n\nexport const PALETTE_TOKENS: Record<PaletteName, ThemeTokens> = ${JSON.stringify(
    palettes,
    null,
    4,
)}\n`

await Bun.write(outputPath, generated)
const formatter = Bun.spawn(
    ["bunx", "biome", "format", "--write", outputPath],
    { stdout: "ignore", stderr: "inherit" },
)
if ((await formatter.exited) !== 0)
    throw new Error("failed to format generated palette table")
console.log(
    `wrote ${outputPath} (${Object.values(palettes).reduce((count, tokens) => count + Object.keys(tokens).length, 0)} palette token entries)`,
)
